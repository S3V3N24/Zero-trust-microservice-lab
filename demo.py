#!/usr/bin/env python3
"""Zero-Trust Microservices Lab - command line entry point.

commands:
  python demo.py                run the full guided demonstration (starts and stops everything itself)
  python demo.py --step         same, but pause before each section (for presenting)
  python demo.py up             start the system and keep it running (dashboard + gateway, Ctrl+C to stop)
  python demo.py bench          compare latency: plain HTTP versus the zero-trust path
  python demo.py test           same checks as the demo, quiet, exit code 1 on any failure (for CI)
  python demo.py token alice    print a user token for curl (needs 'up' running in another terminal)
  python demo.py release api    release a quarantined service (needs 'up' running)
"""
from __future__ import annotations

import argparse
import json
import os
import signal
import sys
import time
import webbrowser

import ssl

if sys.version_info < (3, 9):
    sys.exit('Python 3.9 or newer is required (found %s).' % sys.version.split()[0])
if not ssl.HAS_TLSv1_3:
    sys.exit('This Python build has no TLS 1.3 support (typical for the macOS system Python).\n'
             'Install a current Python from python.org or Homebrew and try again.')
try:
    import cryptography  # noqa: F401
except ImportError:
    sys.exit('The "cryptography" package is missing. Run:  pip install -r requirements.txt')

from zt.common import PORTS, RUNTIME_DIR, SVID_TTL, http_json  # noqa: E402
from zt.scenarios import Lab, run_all  # noqa: E402
from zt.stack import Stack  # noqa: E402

USE_COLOR = sys.stdout.isatty() and os.environ.get('NO_COLOR') is None
if os.name == 'nt':
    os.system('')            # enables ANSI colours in recent Windows terminals


def c(text, code):
    return '\033[%sm%s\033[0m' % (code, text) if USE_COLOR else text


def banner(stack):
    print(c('\n  Zero-Trust Microservices Lab', '1;36'))
    print('  Never trust, always verify: identity, mutual TLS, policy and runtime detection.\n')
    print('  Dashboard (open in a browser):  ' + c('http://127.0.0.1:%d' % PORTS['dashboard'], '1;33'))
    print('  Public gateway (the "app"):     http://127.0.0.1:%d' % PORTS['gateway'])
    print('  Certificate lifetime: %d s (the report uses 1 hour; short here so rotation is visible)\n' % stack.ttl)


def write_report(results, extra=''):
    lines = ['# Test report (prototype)', '',
             'Generated by `python demo.py`. These results come from the Python prototype, not from the Kubernetes testbed.',
             '', '| ID | Scenario | Expected | Observed | Result |', '| --- | --- | --- | --- | --- |']
    for r in results:
        lines.append('| %s | %s | %s | %s | %s |' % (r.tc, r.title, r.expected, r.observed.replace('|', '/'), 'PASS' if r.ok else 'FAIL'))
    passed = sum(r.ok for r in results)
    lines += ['', '**%d of %d checks passed.**' % (passed, len(results))]
    if extra:
        lines += ['', extra]
    path = RUNTIME_DIR / 'report.md'
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path


def cmd_demo(args, quiet=False):
    with Stack(ttl=args.ttl) as stack:
        if not quiet:
            banner(stack)
            if args.open:
                webbrowser.open('http://127.0.0.1:%d' % PORTS['dashboard'])
            if sys.stdin.isatty() and not args.no_pause:
                input(c('  Open the dashboard now, then press Enter to start the walkthrough... ', '33'))
            print()

        def say(text):
            if not quiet:
                if args.step and sys.stdin.isatty():
                    input(c('\n  [Enter] for the next section... ', '33'))
                print(c('\n' + text, '1;36'))

        def show(r):
            if quiet:
                return
            mark = c(' PASS ', '1;42;30') if r.ok else c(' FAIL ', '1;41;37')
            print('%s %-7s %s' % (mark, r.tc, r.title))
            print('        expected: %s' % r.expected)
            print('        observed: %s' % r.observed)

        lab = Lab(stack)
        results = run_all(lab, say, show)
        passed = sum(r.ok for r in results)
        report = write_report(results)
        print(c('\n  %d of %d checks passed.' % (passed, len(results)), '1;32' if passed == len(results) else '1;31'))
        print('  Full report written to %s' % report)
        if args.keep and not quiet:
            print('\n  System is still running. Dashboard: http://127.0.0.1:%d   (Ctrl+C to stop)' % PORTS['dashboard'])
            try:
                while True:
                    time.sleep(1)
            except KeyboardInterrupt:
                pass
        return 0 if passed == len(results) else 1


def cmd_up(args):
    with Stack(ttl=args.ttl) as stack:
        banner(stack)
        if args.open:
            webbrowser.open('http://127.0.0.1:%d' % PORTS['dashboard'])
        print('  Try it from another terminal:')
        print('    python demo.py token alice                       # prints a user token')
        print('    curl -s -X POST http://127.0.0.1:%d/shorten -H "Content-Type: application/json" \\' % PORTS['gateway'])
        print('         -H "Authorization: Bearer <token>" -d \'{"original_url":"https://example.org"}\'')
        print('    curl -s http://127.0.0.1:%d/<alias>' % PORTS['gateway'])
        print('\n  Press Ctrl+C to stop.\n')
        try:
            while True:
                time.sleep(1)
        except KeyboardInterrupt:
            print('\n  Stopping...')
    return 0


def cmd_bench(args):
    from zt.bench import format_table, run_benchmark
    with Stack(log_allow=False, ttl=max(args.ttl, 120)) as stack:
        print(c('\n  Benchmark: plain HTTP versus zero-trust (this takes about 30 seconds)', '1;36'))
        rows = run_benchmark(Lab(stack), say=print)
        table = format_table(rows)
        print('\n' + table + '\n')
        (RUNTIME_DIR / 'benchmark.md').write_text(table + '\n', encoding='utf-8')
        print('  Saved to %s' % (RUNTIME_DIR / 'benchmark.md'))
        print('  Note: numbers are from this Python prototype on this computer, not from Kubernetes.\n')
    return 0


def _secrets():
    try:
        return json.loads((RUNTIME_DIR / 'secrets.json').read_text())
    except OSError:
        sys.exit('No running system found. Start one with:  python demo.py up')


def cmd_token(args):
    from zt import jwtlite
    from zt.common import AUDIENCE, ISSUER
    roles = [r for r in args.roles.split(',') if r]
    print(jwtlite.encode({'iss': ISSUER, 'aud': AUDIENCE, 'sub': args.user, 'roles': roles,
                          'exp': time.time() + args.minutes * 60}, _secrets()['jwt_secret']))
    return 0


def cmd_release(args):
    status, data = http_json(PORTS['controlplane'], 'POST', '/release', {'workload': args.workload},
                             headers={'X-Admin-Token': _secrets()['admin_token']})
    print(status, data)
    return 0 if status == 200 else 1


def main():
    p = argparse.ArgumentParser(description='Zero-Trust Microservices Lab', usage='python demo.py [command] [options]',
                                epilog=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('command', nargs='?', default='demo', choices=['demo', 'up', 'bench', 'test', 'token', 'release'])
    p.add_argument('target', nargs='?', help='user name for "token", service name for "release"')
    p.add_argument('--ttl', type=int, default=SVID_TTL, help='certificate lifetime in seconds (default %d)' % SVID_TTL)
    p.add_argument('--keep', action='store_true', help='demo: keep the system running afterwards')
    p.add_argument('--no-pause', action='store_true', help='demo: do not wait for Enter at the start')
    p.add_argument('--step', action='store_true', help='demo: pause before every section (good for presenting)')
    p.add_argument('--open', action='store_true', help='open the dashboard in a browser')
    p.add_argument('--roles', default='shortener-user', help='token: comma-separated roles')
    p.add_argument('--minutes', type=int, default=30, help='token: validity in minutes')
    args = p.parse_args()
    try:                                   # make "kill" behave like Ctrl+C so child processes are cleaned up
        signal.signal(signal.SIGTERM, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))
    except (ValueError, OSError):
        pass
    if args.command == 'token':
        args.user = args.target or 'alice'
        return cmd_token(args)
    if args.command == 'release':
        if not args.target:
            p.error('release needs a service name: db, cache, api or gateway')
        args.workload = args.target
        return cmd_release(args)
    if args.command == 'test':
        args.keep = args.no_pause = args.open = args.step = False
        return cmd_demo(args, quiet=True)
    return {'demo': cmd_demo, 'up': cmd_up, 'bench': cmd_bench}[args.command](args)


if __name__ == '__main__':
    sys.exit(main())
